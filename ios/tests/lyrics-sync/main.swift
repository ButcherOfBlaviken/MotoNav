import Foundation
var checks = 0
func check(_ v: Bool, _ reason: String) { precondition(v, reason); checks += 1 }
var sync = LyricsDisplaySync()
check(sync.command(now: 0, ready: false) == nil, "wait for link")
check(sync.command(now: 1, ready: true) == "#ML,0", "default OFF even before HID capability")
check(sync.command(now: 2, ready: true) == nil, "throttle pending command")
check(sync.command(now: 3, ready: true) == "#ML,0", "retry dropped OFF")
sync.acknowledge(false)
check(sync.command(now: 5, ready: true) == nil, "ack ends retries")
sync.configure(true)
check(sync.command(now: 6, ready: true) == "#ML,1", "turn on")
sync.configure(false)
check(sync.command(now: 6.1, ready: true) == "#ML,0", "OFF supersedes pending ON")
sync.acknowledge(true)
check(sync.desired == false, "stale ON ack cannot enable lyrics")
check(sync.command(now: 8.1, ready: true) == "#ML,0", "repair stale ON ack")
sync.acknowledge(false)
check(sync.command(now: 10.1, ready: true) == nil, "OFF confirmed")
sync.reset()
check(sync.command(now: 11, ready: true) == "#ML,0", "reconnect resends latest setting")
sync.configure(false, force: true)
check(sync.command(now: 11.1, ready: true) == "#ML,0", "force-clear repeated OFF")
print("Lyrics switch recovery: \(checks) checks passed")
